import pg from "pg";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { resolve } from "node:path";
import { applyMigrations } from "../../dist/infrastructure/storage/postgres/migration-runner.js";
import { productSiteContext } from "../../tests/helpers/product-site-context.mjs";
import { PostgresSiteCommerceRepository } from "../../dist/infrastructure/storage/postgres/postgres-site-commerce-repository.js";
import { PostgresCommerceOrderRepository } from "../../dist/infrastructure/storage/postgres/postgres-commerce-order-repository.js";
import { SandboxPaymentProvider } from "../../dist/infrastructure/commerce/payment-providers.js";
import { OwnShippingProvider } from "../../dist/infrastructure/commerce/shipping-providers.js";
import { siteContentSchema, siteThemeSchema } from "../../dist/domain/sites/site.model.js";
import { defaultProductDetails } from "../../dist/domain/products/product-details.js";
import { publishSite } from "../../dist/application/sites/site-use-cases.js";
import { saveSiteCommerceSettings, setPublicCartItem } from "../../dist/application/sites/site-commerce-use-cases.js";
import { placeOrder, siteCheckoutStatus, simulateSandboxPayment, cancelOrder } from "../../dist/application/commerce/checkout-use-cases.js";

const url = process.env.READINESS_QA_DATABASE_URL;
if (!url || !/^\/vorix_readiness_qa(?:_|$)/.test(new URL(url).pathname) || !["127.0.0.1", "localhost"].includes(new URL(url).hostname)) throw Error("LOCAL_DISPOSABLE_READINESS_DATABASE_REQUIRED");
const pool = new pg.Pool({ connectionString: url, max: 10 });
try {
  await applyMigrations(pool, resolve("db/migrations"));
  const c = await productSiteContext(pool), commerceRepository = new PostgresSiteCommerceRepository(pool), orders = new PostgresCommerceOrderRepository(pool);
  const deps = { ...c.siteDeps, commerceRepository, orders, sandboxAllowed: true, paymentProviders: { SANDBOX: new SandboxPaymentProvider() }, shippingProviders: { OWN: new OwnShippingProvider() } };
  deps.checkoutStatus = (site, settings) => siteCheckoutStatus(deps, site, settings);
  const site = await c.siteDeps.repository.create({ ...c.scope, slug: "qa-concurrency-" + randomUUID().slice(0, 8), draft: { content: siteContentSchema.parse({ name: "QA concorrência", blocks: [{ id: "catalog", type: "catalog", title: "Catálogo" }] }), theme: siteThemeSchema.parse({}) } });
  await publishSite(deps, { ...c.scope, id: site.id, revision: site.revision, actorUserId: c.actor.userId });
  await saveSiteCommerceSettings(deps, { site, settings: { mode: "HYBRID", checkout: { payment: { provider: "SANDBOX" }, shipping: { pickup: { enabled: true, address: "Endereço QA" } } } }, actorUserId: c.actor.userId });
  const product = await c.product({ name: "Última unidade QA", priceCents: 1000, trackStock: true, details: { ...defaultProductDetails(), siteVisible: true } });
  await c.d.productEngineRepository.move({ ...c.scope, productId: product.id, kind: "IN", quantity: 1, operationKey: randomUUID(), userId: c.actor.userId });
  const lookup = { slug: site.slug }, cart = async () => (await setPublicCartItem(deps, { lookup, productId: product.id, quantity: 1 })).token;
  const tokens = await Promise.all([cart(), cart()]);
  const submit = (token, requestKey = randomUUID()) => placeOrder(deps, { lookup, token, requestKey, customer: { name: "Comprador QA", email: "buyer@qa.invalid", phone: "11999990000" }, deliveryOptionId: "pickup", payment: { method: "SANDBOX" } });
  const results = await Promise.allSettled(tokens.map(token => submit(token)));
  assert.equal(results.filter(r => r.status === "fulfilled").length, 1, JSON.stringify(results.map(r => r.reason?.message)));
  assert.equal(results.filter(r => r.status === "rejected").length, 1);
  const stock = async () => (await pool.query("select stock_quantity::int stock,reserved_quantity::int reserved from products where id=$1", [product.id])).rows[0];
  assert.deepEqual(await stock(), { stock: 1, reserved: 1 });
  const placed = results.find(r => r.status === "fulfilled").value;
  const id = (await pool.query("select id from commerce_orders where workspace_id=$1 and number=$2", [c.workspaceId, placed.number])).rows[0].id;
  const scope = { ...c.scope, actorUserId: c.actor.userId };
  await simulateSandboxPayment(deps, scope, { id, outcome: "APPROVED" });
  await simulateSandboxPayment(deps, scope, { id, outcome: "APPROVED" });
  assert.deepEqual(await stock(), { stock: 0, reserved: 0 });
  await cancelOrder(deps, scope, { id, reason: "QA controlled refund" });
  assert.deepEqual(await stock(), { stock: 1, reserved: 0 });
  const token = await cart(), key = randomUUID();
  const repeated = await Promise.all([submit(token, key), submit(token, key)]);
  assert.equal(repeated[0].number, repeated[1].number);
  const count = Number((await pool.query("select count(*) n from commerce_orders where site_id=$1 and request_key=$2", [site.id, key])).rows[0].n);
  assert.equal(count, 1); assert.deepEqual(await stock(), { stock: 1, reserved: 1 });
  console.log(JSON.stringify({ database: "disposable-real-postgresql", overselling: "PASS", repeatedApproval: "PASS", refundAndRestock: "PASS", concurrentIdempotency: "PASS", providers: "VORIX_SANDBOX_ONLY" }));
} finally { await pool.end(); }
